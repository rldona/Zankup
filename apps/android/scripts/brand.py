#!/usr/bin/env python3
"""Writes the Zankup mark and wordmark as vector drawables, from docs/brand/assets (the source of truth).

- core/designsystem: zankup_mark.xml and zankup_wordmark.xml, one colour (tinted where they are drawn).
- app: the adaptive launcher icon's foreground (white mark in the safe zone), the splash icon and the
  notifications' small icon; and the launcher icon's variants (apps/mobile/plugins/appIcons.json, as the
  React Native app offers them): a background, a foreground and an adaptive icon each (OS-1171).
Usage: scripts/brand.py (run it when the brand assets change).
"""

import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
BRAND = ROOT / "docs/brand/assets"
DS = HERE.parent / "core/designsystem/src/main/res/drawable"
APP = HERE.parent / "app/src/main/res/drawable"
MIPMAP = HERE.parent / "app/src/main/res/mipmap-anydpi"
ICONS = ROOT / "apps/mobile/plugins/appIcons.json"
NOTE = "<!-- Generated by scripts/brand.py from docs/brand/assets: do not edit. -->"


def attrs(svg: str, tag: str) -> dict[str, str]:
    match = re.search(rf"<{tag}\b([^>]*)/?>", svg)
    if not match:
        raise SystemExit(f"no <{tag}>")
    return dict(re.findall(r'([A-Za-z-]+)="([^"]*)"', match.group(1)))


def vector(width: str, height: str, vw: float, vh: float, body: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
{NOTE}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width}"
    android:height="{height}"
    android:viewportWidth="{vw:g}"
    android:viewportHeight="{vh:g}">
{body}
</vector>
"""


def mark_path(d: str, width: str, color: str, indent: str = "    ") -> str:
    return (
        f'{indent}<path\n{indent}    android:pathData="{d}"\n{indent}    android:strokeColor="{color}"\n'
        f'{indent}    android:strokeWidth="{width}"\n{indent}    android:strokeLineCap="butt"\n'
        f'{indent}    android:fillColor="#00000000" />'
    )


def main() -> None:
    mark_svg = (BRAND / "logo-mark.svg").read_text()
    _, _, mw, mh = (float(v) for v in attrs(mark_svg, "svg")["viewBox"].split())
    mark = attrs(mark_svg, "path")
    word_svg = (BRAND / "wordmark.svg").read_text()
    _, _, ww, wh = (float(v) for v in attrs(word_svg, "svg")["viewBox"].split())
    word = attrs(word_svg, "path")["d"]

    DS.mkdir(parents=True, exist_ok=True)
    APP.mkdir(parents=True, exist_ok=True)
    (DS / "zankup_mark.xml").write_text(
        vector("24dp", f"{24 * mh / mw:.2f}dp", mw, mh, mark_path(mark["d"], mark["stroke-width"], "#FF000000"))
    )
    (DS / "zankup_wordmark.xml").write_text(
        vector(
            "110dp",
            f"{110 * wh / ww:.2f}dp",
            ww,
            wh,
            f'    <path\n        android:pathData="{word}"\n        android:fillColor="#FF000000" />',
        )
    )

    # The launcher's foreground and the splash: 108 dp canvases, the mark 46 dp tall in the middle (well
    # inside the 66 dp safe zone, as the current icon).
    def centred(height: float, color: str = "#FFFFFFFF") -> str:
        scale = height / mh
        tx, ty = (108 - mw * scale) / 2, (108 - mh * scale) / 2
        path = mark_path(mark["d"], mark["stroke-width"], color, "        ")
        return (
            f'    <group\n        android:scaleX="{scale:.5f}"\n        android:scaleY="{scale:.5f}"\n'
            f'        android:translateX="{tx:.3f}"\n        android:translateY="{ty:.3f}">\n{path}\n    </group>'
        )

    (APP / "ic_launcher_foreground.xml").write_text(vector("108dp", "108dp", 108, 108, centred(46)))
    (APP / "ic_splash.xml").write_text(vector("108dp", "108dp", 108, 108, centred(40)))
    # The status bar's small icon: the mark alone, filling the 24 dp square (Android tints it).
    (APP / "ic_notification.xml").write_text(vector("24dp", "24dp", 108, 108, centred(92)))

    # The launcher icon's variants: each its background (one colour, or stripes for pride) and its mark.
    MIPMAP.mkdir(parents=True, exist_ok=True)
    for variant in json.loads(ICONS.read_text())["variants"]:
        name = variant["name"]
        if name == "default":
            continue
        colours = variant["background"]
        # The launcher shows only the middle 72 of the 108 dp (the rest is masked), so the stripes share
        # that part, the first and the last stretched to the edges: every colour stays in sight.
        band = 72 / len(colours)
        edges = [0.0] + [18 + band * i for i in range(1, len(colours))] + [108.0]
        rects = "\n".join(
            f'    <path\n        android:pathData="M0,{round(edges[i], 2):g}h108v{round(edges[i + 1] - edges[i], 2):g}h-108z"\n'
            f'        android:fillColor="{c.upper()}" />'
            for i, c in enumerate(colours)
        )
        (APP / f"ic_launcher_bg_{name}.xml").write_text(vector("108dp", "108dp", 108, 108, rects))
        (APP / f"ic_launcher_fg_{name}.xml").write_text(
            vector("108dp", "108dp", 108, 108, centred(46, "#FF" + variant["mark"].lstrip("#").upper()))
        )
        (MIPMAP / f"ic_launcher_{name}.xml").write_text(
            f"""<?xml version="1.0" encoding="utf-8"?>
{NOTE}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg_{name}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_{name}" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""
        )
    print("brand drawables written")


if __name__ == "__main__":
    main()
