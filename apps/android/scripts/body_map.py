#!/usr/bin/env python3
"""Writes the body map's data for Android from packages/core/src/domain/strength.ts (the source of truth,
shared with the PWA and the React Native app): the muscles, what each exercise and workout kind works,
and the figure's shapes, as core/ui's BodyData.kt.

Usage: uv run --no-project python scripts/body_map.py (needs bun; run it when strength.ts changes).
"""

import json
import pathlib
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
SOURCE = ROOT / "packages/core/src/domain/strength.ts"
OUT = HERE.parent / "core/ui/src/main/kotlin/com/zankup/android/ui/body/BodyData.kt"

DUMP = f"""
import * as s from {json.dumps(str(SOURCE))};
console.log(JSON.stringify({{
  front: s.FRONT, back: s.BACK, exercises: s.EXERCISE_MUSCLES, workouts: s.WORKOUT_MUSCLES,
  shapes: s.BODY_SHAPES, detail: s.BODY_DETAIL, silhouette: s.BODY_SILHOUETTE,
}}));
"""


def kt(value: str) -> str:
    return json.dumps(value)


def main() -> None:
    data = json.loads(subprocess.run(["bun", "-e", DUMP], check=True, capture_output=True, text=True).stdout)
    muscles = list(dict.fromkeys(data["front"] + data["back"]))
    enum = lambda m: m.upper()  # noqa: E731
    lines = [
        "// Generated by scripts/body_map.py from packages/core/src/domain/strength.ts: do not edit.",
        "@file:Suppress(\"ktlint\")",
        "",
        "package com.zankup.android.ui.body",
        "",
        "/** The muscle groups the body map draws, with their keys in the API and the catalogues. */",
        "enum class Muscle(val key: String) {",
        ",\n".join(f"    {enum(m)}({kt(m)})" for m in muscles),
        "}",
        "",
        "internal val FRONT = listOf(" + ", ".join(f"Muscle.{enum(m)}" for m in data["front"]) + ")",
        "",
        "internal val BACK = listOf(" + ", ".join(f"Muscle.{enum(m)}" for m in data["back"]) + ")",
        "",
        "/** The FIT exercise categories and the muscle groups they mainly work. */",
        "internal val EXERCISE_MUSCLES: Map<String, List<Muscle>> = mapOf(",
        ",\n".join(
            f"    {kt(k)} to listOf(" + ", ".join(f"Muscle.{enum(m)}" for m in v) + ")"
            for k, v in data["exercises"].items()
        ),
        ")",
        "",
        "/** Each workout kind's muscles, weighted as sets would be. */",
        "internal val WORKOUT_MUSCLES: Map<String, Map<Muscle, Int>> = mapOf(",
        ",\n".join(
            f"    {kt(k)} to mapOf(" + ", ".join(f"Muscle.{enum(m)} to {n}" for m, n in v.items()) + ")"
            for k, v in data["workouts"].items()
        ),
        ")",
        "",
        "/** Each side's muscle shapes (SVG path data on a 100 × 200 box). */",
        "internal val BODY_SHAPES: Map<String, Map<Muscle, List<String>>> = mapOf(",
        ",\n".join(
            f"    {kt(side)} to mapOf(\n"
            + ",\n".join(
                f"        Muscle.{enum(m)} to listOf(\n" + ",\n".join(f"            {kt(d)}" for d in paths) + "\n        )"
                for m, paths in shapes.items()
            )
            + "\n    )"
            for side, shapes in data["shapes"].items()
        ),
        ")",
        "",
        "/** Shapes never worked (the inner thighs), so the figure reads as a body. */",
        "internal val BODY_DETAIL: Map<String, List<String>> = mapOf(",
        ",\n".join(f"    {kt(side)} to listOf(" + ", ".join(kt(d) for d in ds) + ")" for side, ds in data["detail"].items()),
        ")",
        "",
        "/** The figure's outline: head and body. */",
        f"internal const val BODY_SILHOUETTE = {kt(data['silhouette'])}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(HERE.parent)}: {len(muscles)} muscles")


if __name__ == "__main__":
    main()
