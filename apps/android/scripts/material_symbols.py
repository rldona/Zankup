#!/usr/bin/env python3
"""Writes the Material Symbols listed in icons.txt as vector drawables of core:designsystem.

Material Symbols is Apache 2.0. Each icon is fetched from Google Fonts as an SVG (viewBox 0 -960 960 960)
and written as res/drawable/ic_<name>.xml (and ic_<name>_fill.xml). Usage: scripts/material_symbols.py
"""

import pathlib
import re
import sys
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "core/designsystem/src/main/res/drawable"
URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{style}/24px.svg"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}"{fill} (Apache 2.0). Generated by scripts/material_symbols.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="#FF000000"
            android:pathData="{d}" />
    </group>
</vector>
"""


def fetch(name: str, style: str) -> str:
    with urllib.request.urlopen(URL.format(name=name, style=style), timeout=20) as response:
        svg = response.read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f"{name} ({style}): no path in the SVG")
    return "".join(paths)


def main() -> int:
    wanted: list[tuple[str, bool]] = []
    for line in (HERE / "icons.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, *rest = line.split()
            wanted.append((name, rest == ["fill"]))
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("ic_*.xml"):
        old.unlink()
    for name, fill in wanted:
        styles = [("default", "")] + ([("fill1", "_fill")] if fill else [])
        for style, suffix in styles:
            d = fetch(name, style)
            text = TEMPLATE.format(name=name, fill=" filled" if suffix else "", d=d)
            (OUT / f"ic_{name}{suffix}.xml").write_text(text)
    print(f"{len(wanted)} icons in {OUT.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
