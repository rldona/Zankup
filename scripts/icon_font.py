"""Builds the mobile app's icon font from the Material Symbols in packages/core (src/icons/material.ts).

Each icon becomes one glyph of an OpenType (CFF) font, so the app draws an icon as a character of text
instead of a Skia canvas per icon: one native view less for each of the dozens of icons on a screen.
The glyphs keep the paths' cubic curves and their 960-unit box, with the box as the font's em (ascent
960, descent 0), so a glyph set at a font size fills a square of that size exactly.

Run after scripts/material_icons.py changes the icons:

    uv run --with fonttools python scripts/icon_font.py

It writes apps/mobile/assets/fonts/ZankupIcons.otf and apps/mobile/src/iconGlyphs.ts.
"""

from __future__ import annotations

import re
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "packages/core/src/icons/material.ts"
FONT = ROOT / "apps/mobile/assets/fonts/ZankupIcons.otf"
GLYPHS = ROOT / "apps/mobile/src/iconGlyphs.ts"
FAMILY = "ZankupIcons"
EM = 960
FIRST = 0xE000  # the Private Use Area: no character of any language


def icons() -> list[tuple[str, str]]:
    text = SOURCE.read_text()
    return re.findall(r"^\s+'?([a-z0-9_-]+)'?:\s*\n?\s*'([^']+)'", text, re.MULTILINE)


def key(name: str) -> str:
    """A name as a TypeScript key: quoted when it has a hyphen (`home-fill`)."""
    return name if re.fullmatch(r"[a-z_][a-z0-9_]*", name) else f"'{name}'"


def main() -> None:
    found = icons()
    names = [".notdef"] + [name for name, _ in found]
    charstrings = {}
    empty = T2CharStringPen(EM, None)
    charstrings[".notdef"] = empty.getCharString()
    for name, d in found:
        pen = T2CharStringPen(EM, None)
        # SVG's y grows down, from -960 (top) to 0 (bottom); a font's grows up from the baseline.
        parse_path(d, TransformPen(pen, (1, 0, 0, -1, 0, 0)))
        charstrings[name] = pen.getCharString()
    cmap = {FIRST + i: name for i, (name, _) in enumerate(found)}

    fb = FontBuilder(EM, isTTF=False)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupCFF(FAMILY, {"FullName": FAMILY}, charstrings, {})
    fb.setupHorizontalMetrics({name: (EM, 0) for name in names})
    fb.setupHorizontalHeader(ascent=EM, descent=0)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    fb.setupOS2(
        sTypoAscender=EM, sTypoDescender=0, sTypoLineGap=0, usWinAscent=EM, usWinDescent=0, fsType=0
    )
    fb.setupPost()
    FONT.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(FONT))

    lines = [
        "/**",
        " * Each icon's character in the icon font (assets/fonts/ZankupIcons.otf).",
        " * Generated by scripts/icon_font.py: do not edit.",
        " */",
        "export const ICON_GLYPHS = {",
        *[f"  {key(name)}: '\\u{code:04x}'," for code, name in cmap.items()],
        "} as const;",
        "",
    ]
    GLYPHS.write_text("\n".join(lines))
    print(f"{len(found)} icons → {FONT.relative_to(ROOT)} ({FONT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
